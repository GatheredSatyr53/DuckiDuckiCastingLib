using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Collections.Immutable;

namespace DuckiDuckiCastingLib
{
    /// <summary>
    /// Duck-typing generator. For every interface marked with <c>[SupportsDuckCast]</c> it emits a partial
    /// part containing <c>static IFoo Cast&lt;TSource&gt;(TSource source)</c>, finds every <c>IFoo.Cast(x)</c>
    /// call in the compilation and generates an adapter class per distinct static argument type
    /// (in <c>DuckiDuckiCastingLib.Generated</c>); <c>Cast</c> dispatches on <c>typeof(TSource)</c>.
    /// </summary>
    /// <remarks>
    /// Pipeline:
    /// <code>
    ///   [SupportsDuckCast] interfaces ──► InterfaceModel ──┐
    ///                                                      ├─ Collect + Combine ─► SelectMany ─► GenerationUnit ─► source + diagnostics
    ///   IFoo.Cast(x) call sites ──► CastSiteResult ─┬─────┘   (adapters grouped per interface)
    ///                                               └─ diagnostics (DUCK002/3/6)
    /// </code>
    /// Every value flowing between stages is an equatable record (see <c>Models.cs</c>), so unchanged
    /// interfaces are not regenerated when unrelated code changes.
    /// </remarks>
    [Generator(LanguageNames.CSharp)]
    internal sealed class DuckCastGenerator : IIncrementalGenerator
    {
        public const string ANNOTATIONS = "DuckiDuckiCastingLib.Annotations";
        public const string SupportsDuckCastAttributeName = "SupportsDuckCastAttribute";
        public const string AttributeFullName = ANNOTATIONS + "." + SupportsDuckCastAttributeName;
        public const string CastMethodName = "Cast";

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            context.RegisterPostInitializationOutput(static ctx =>
            {
                ctx.AddSource($"{SupportsDuckCastAttributeName}.g.cs", $$"""
                    // <auto-generated/>
                    #nullable enable

                    namespace {{ANNOTATIONS}}
                    {
                        /// <summary>
                        /// Marks a partial interface as a duck-typing target: a static <c>Cast&lt;TSource&gt;(TSource source)</c>
                        /// method is generated into it, and every <c>Cast</c> call in this assembly gets an adapter
                        /// for the static type of its argument.
                        /// </summary>
                        [global::System.AttributeUsage(global::System.AttributeTargets.Interface)]
                        [global::System.Diagnostics.Conditional("DUCKCAST_KEEP_ATTRIBUTES")]
                        internal sealed class {{SupportsDuckCastAttributeName}} : global::System.Attribute
                        {
                        }
                    }
                    """);
            });

            // Stage 1: every interface carrying [SupportsDuckCast].
            IncrementalValuesProvider<InterfaceModel> interfaces = context.SyntaxProvider
                .ForAttributeWithMetadataName(
                    AttributeFullName,
                    predicate: static (node, _) => node is InterfaceDeclarationSyntax,
                    transform: static (ctx, cancellationToken) => ModelBuilder.BuildInterface(ctx, cancellationToken))
                .WithTrackingName(TrackingNames.Interfaces);

            // Stage 2: every IFoo.Cast(x) / IFoo.Cast<T>(x) call whose receiver is such an interface.
            IncrementalValuesProvider<CastSiteResult> castSites = context.SyntaxProvider
                .CreateSyntaxProvider(
                    predicate: static (node, _) => ModelBuilder.IsCastInvocation(node),
                    transform: static (ctx, cancellationToken) => ModelBuilder.BuildCastSite(ctx, cancellationToken))
                .Where(static result => result is not null)
                .Select(static (result, _) => result!)
                .WithTrackingName(TrackingNames.CastSites);

            // Call-site problems are reported per site; they carry no syntax, only an equatable location.
            context.RegisterSourceOutput(
                castSites.Where(static site => site.Diagnostic is not null),
                static (spc, site) => spc.ReportDiagnostic(site.Diagnostic!.ToDiagnostic()));

            // Stage 3: hand the collected adapters to their interfaces. Collect/Combine is the only way to
            // join two providers; SelectMany splits the result back into one unit per interface so the
            // output step below is cached per interface.
            IncrementalValueProvider<ImmutableArray<AdapterModel>> adapters = castSites
                .Where(static site => site.Adapter is not null)
                .Select(static (site, _) => site.Adapter!)
                .Collect();

            IncrementalValuesProvider<GenerationUnit> units = interfaces
                .Collect()
                .Combine(adapters)
                .SelectMany(static (pair, _) => ModelBuilder.Join(pair.Left, pair.Right))
                .WithTrackingName(TrackingNames.Units);

            // Stage 4: Cast<TSource> plus adapters, one file per interface.
            context.RegisterSourceOutput(units, static (spc, unit) => Emitter.Emit(spc, unit));
        }
    }

    /// <summary>Step names for <c>GeneratorDriver</c> tests that assert incremental caching.</summary>
    internal static class TrackingNames
    {
        public const string Interfaces = "DuckInterfaces";
        public const string CastSites = "DuckCastSites";
        public const string Units = "DuckUnits";
    }
}
