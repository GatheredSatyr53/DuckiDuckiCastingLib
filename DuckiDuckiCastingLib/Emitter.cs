using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace DuckiDuckiCastingLib
{
    /// <summary>
    /// Output stage: turns a <see cref="GenerationUnit"/> into the partial interface part that holds
    /// <c>Cast&lt;TSource&gt;</c>, plus one adapter class per source type inside
    /// <c>DuckiDuckiCastingLib.Generated.&lt;Interface&gt;_DuckAdapters</c>. (Adapters cannot be nested in the
    /// interface itself: that is illegal for variant interfaces, CS8427.)
    /// Works on models only, so it is deterministic and unit-testable without a compilation.
    /// </summary>
    internal static class Emitter
    {
        private const string SourceField = "__duck";
        private const string GeneratedNamespace = "DuckiDuckiCastingLib.Generated";

        public static void Emit(SourceProductionContext context, GenerationUnit unit)
        {
            foreach (DiagnosticInfo diagnostic in unit.Interface.Diagnostics)
            {
                context.ReportDiagnostic(diagnostic.ToDiagnostic());
            }

            if (!unit.Interface.CanGenerate)
            {
                return;
            }

            context.CancellationToken.ThrowIfCancellationRequested();
            context.AddSource(unit.Interface.HintName, SourceText.From(Render(unit), Encoding.UTF8));
        }

        public static string Render(GenerationUnit unit)
        {
            InterfaceModel iface = unit.Interface;
            var writer = new CodeWriter();

            writer.Line("// <auto-generated/>");
            writer.Line("// Generated by DuckiDuckiCastingLib. Changes will be overwritten.");
            writer.Line("#nullable enable");
            writer.Line("#pragma warning disable");
            writer.Line();

            if (iface.Namespace is not null)
            {
                writer.Line($"namespace {iface.Namespace}");
                writer.Open();
            }

            foreach (ContainingType outer in iface.ContainingTypes)
            {
                writer.Line($"partial {outer.Keyword} {Id(outer.Name)}{TypeParameterList(outer.TypeParameters)}");
                writer.Open();
            }

            // The interface's own name as usable inside its body, e.g. IFoo<T>.
            string self = Id(iface.Name) + TypeArgumentList(iface.TypeParameters);

            writer.Line($"partial interface {Id(iface.Name)}{TypeParameterList(iface.TypeParameters)}");
            writer.Open();
            WriteCast(writer, iface, self, unit.Adapters);
            writer.Close();

            foreach (ContainingType _ in iface.ContainingTypes)
            {
                writer.Close();
            }

            if (iface.Namespace is not null)
            {
                writer.Close();
            }

            if (unit.Adapters.Count > 0)
            {
                writer.Line();
                writer.Line($"namespace {GeneratedNamespace}");
                writer.Open();
                writer.Line($"internal static class {iface.AdaptersClassName}");
                writer.Open();
                for (int i = 0; i < unit.Adapters.Count; i++)
                {
                    if (i > 0)
                    {
                        writer.Line();
                    }

                    WriteAdapter(writer, unit.Adapters[i]);
                }

                writer.Close();
                writer.Close();
            }

            return writer.ToString();
        }

        private static void WriteCast(CodeWriter writer, InterfaceModel iface, string self, EquatableList<AdapterModel> adapters)
        {
            string tSource = UniqueTypeParameterName("TSource", iface);
            List<DuckTypeParameter> typeParametersInScope = AllTypeParameters(iface);
            bool isGeneric = typeParametersInScope.Count > 0;

            writer.Line("/// <summary>");
            writer.Line($"/// Adapts <paramref name=\"source\"/> to <see cref=\"{CrefName(iface)}\"/> through an adapter generated by DuckiDuckiCastingLib.");
            writer.Line("/// Adapters exist only for the argument types that appear in Cast calls within this assembly.");
            writer.Line("/// </summary>");
            writer.Line("/// <exception cref=\"global::System.ArgumentNullException\"><paramref name=\"source\"/> is <see langword=\"null\"/>.</exception>");
            writer.Line($"/// <exception cref=\"global::System.InvalidCastException\">No adapter was generated for <typeparamref name=\"{tSource}\"/>.</exception>");
            writer.Line($"public static {self} {DuckCastGenerator.CastMethodName}<{tSource}>({tSource} source)");
            writer.Open();

            writer.Line("if (source is null)");
            writer.Open();
            writer.Line("throw new global::System.ArgumentNullException(nameof(source));");
            writer.Close();

            writer.Line($"if (source is {self} alreadyImplemented)");
            writer.Open();
            writer.Line("return alreadyImplemented;");
            writer.Close();

            foreach (AdapterModel adapter in adapters)
            {
                // Dispatch on the static types seen at the call sites: the interface's type arguments and TSource.
                var conditions = new List<string>();
                for (int i = 0; i < typeParametersInScope.Count; i++)
                {
                    conditions.Add($"typeof({Id(typeParametersInScope[i].Name)}) == typeof({adapter.InterfaceTypeArguments[i]})");
                }

                conditions.Add($"typeof({tSource}) == typeof({adapter.SourceType})");

                writer.Line($"if ({string.Join(" && ", conditions)})");
                writer.Open();
                string instance = $"new global::{GeneratedNamespace}.{iface.AdaptersClassName}.{adapter.AdapterName}(({adapter.SourceType})(object)source)";
                writer.Line(isGeneric ? $"return ({self})(object){instance};" : $"return {instance};");
                writer.Close();
            }

            writer.Line("throw new global::System.InvalidCastException(");
            writer.Indent();
            writer.Line($"\"No duck-cast adapter from '\" + typeof({tSource}) + \"' to '\" + typeof({self}) + \"' was generated. \" +");
            writer.Line($"\"Call {Id(iface.Name)}.{DuckCastGenerator.CastMethodName} with an argument whose static type is the type to adapt.\");");
            writer.Outdent();

            writer.Close();
        }

        private static void WriteAdapter(CodeWriter writer, AdapterModel adapter)
        {
            writer.Line($"internal sealed class {adapter.AdapterName} : {adapter.InterfaceType}");
            writer.Open();

            // Not readonly: setters on a struct source must mutate the stored copy, not a defensive copy.
            writer.Line($"private {adapter.SourceType} {SourceField};");
            writer.Line();
            writer.Line($"public {adapter.AdapterName}({adapter.SourceType} source)");
            writer.Open();
            writer.Line($"{SourceField} = source;");
            writer.Close();

            // Everything is implemented explicitly: that copes with same-named members coming from
            // different base interfaces and needs no constraint clauses on generic methods.
            foreach (DuckMethod method in adapter.Methods)
            {
                writer.Line();
                string typeParameters = method.TypeParameters.Count == 0
                    ? string.Empty
                    : "<" + string.Join(", ", method.TypeParameters.Select(Id)) + ">";
                writer.Line(
                    $"{method.ReturnType} {method.DeclaringInterface}.{Id(method.Name)}{typeParameters}({ParameterList(method.Parameters)})"
                    + $" => {SourceField}.{Id(method.Name)}{typeParameters}({ArgumentList(method.Parameters)});");
            }

            foreach (DuckProperty property in adapter.Properties)
            {
                writer.Line();
                string header;
                string target;
                if (property.IsIndexer)
                {
                    header = $"{property.Type} {property.DeclaringInterface}.this[{ParameterList(property.Parameters)}]";
                    target = $"{SourceField}[{ArgumentList(property.Parameters)}]";
                }
                else
                {
                    header = $"{property.Type} {property.DeclaringInterface}.{Id(property.Name)}";
                    target = $"{SourceField}.{Id(property.Name)}";
                }

                writer.Line(header);
                writer.Open();
                if (property.HasGetter)
                {
                    writer.Line($"get => {target};");
                }

                if (property.HasSetter)
                {
                    writer.Line($"{(property.IsInitOnly ? "init" : "set")} => {target} = value;");
                }

                writer.Close();
            }

            foreach (DuckEvent @event in adapter.Events)
            {
                writer.Line();
                writer.Line($"event {@event.Type} {@event.DeclaringInterface}.{Id(@event.Name)}");
                writer.Open();
                writer.Line($"add => {SourceField}.{Id(@event.Name)} += value;");
                writer.Line($"remove => {SourceField}.{Id(@event.Name)} -= value;");
                writer.Close();
            }

            writer.Close();
        }

        private static string ParameterList(EquatableList<DuckParameter> parameters)
            => string.Join(", ", parameters.Select(p => DeclarationModifier(p.RefKind) + p.Type + " " + Id(p.Name)));

        private static string ArgumentList(EquatableList<DuckParameter> parameters)
            => string.Join(", ", parameters.Select(p => ArgumentModifier(p.RefKind) + Id(p.Name)));

        private static string DeclarationModifier(RefKind refKind) => refKind switch
        {
            RefKind.Ref => "ref ",
            RefKind.Out => "out ",
            RefKind.In => "in ",
            RefKind.RefReadOnlyParameter => "ref readonly ",
            _ => string.Empty,
        };

        // 'in' is optional at a call site and omitting it also allows forwarding to a by-value parameter.
        private static string ArgumentModifier(RefKind refKind) => refKind switch
        {
            RefKind.Ref => "ref ",
            RefKind.Out => "out ",
            RefKind.RefReadOnlyParameter => "in ",
            _ => string.Empty,
        };

        private static string TypeParameterList(EquatableList<DuckTypeParameter> typeParameters)
            => typeParameters.Count == 0
                ? string.Empty
                : "<" + string.Join(", ", typeParameters.Select(tp => Variance(tp.Variance) + Id(tp.Name))) + ">";

        private static string TypeArgumentList(EquatableList<DuckTypeParameter> typeParameters)
            => typeParameters.Count == 0
                ? string.Empty
                : "<" + string.Join(", ", typeParameters.Select(tp => Id(tp.Name))) + ">";

        private static string Variance(VarianceKind variance) => variance switch
        {
            VarianceKind.Out => "out ",
            VarianceKind.In => "in ",
            _ => string.Empty,
        };

        private static string CrefName(InterfaceModel iface)
            => iface.TypeParameters.Count == 0
                ? Id(iface.Name)
                : Id(iface.Name) + "{" + string.Join(", ", iface.TypeParameters.Select(tp => Id(tp.Name))) + "}";

        /// <summary>Type parameters visible inside the interface body: containing types' (outermost first), then its own.</summary>
        private static List<DuckTypeParameter> AllTypeParameters(InterfaceModel iface)
        {
            var result = new List<DuckTypeParameter>();
            foreach (ContainingType outer in iface.ContainingTypes)
            {
                result.AddRange(outer.TypeParameters);
            }

            result.AddRange(iface.TypeParameters);
            return result;
        }

        /// <summary>A type parameter name for Cast that clashes with no type parameter in scope.</summary>
        private static string UniqueTypeParameterName(string preferred, InterfaceModel iface)
        {
            var inScope = new HashSet<string>(AllTypeParameters(iface).Select(tp => tp.Name));
            string name = preferred;
            while (inScope.Contains(name))
            {
                name += "_";
            }

            return name;
        }

        /// <summary>Escapes identifiers that happen to be C# keywords (<c>@class</c>).</summary>
        private static string Id(string name)
            => SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None ? "@" + name : name;

        private sealed class CodeWriter
        {
            private readonly StringBuilder _builder = new();
            private int _depth;

            public void Line(string text = "")
            {
                if (text.Length == 0)
                {
                    _builder.AppendLine();
                    return;
                }

                _builder.Append(' ', _depth * 4).AppendLine(text);
            }

            public void Open()
            {
                Line("{");
                _depth++;
            }

            public void Close()
            {
                _depth--;
                Line("}");
            }

            public void Indent() => _depth++;

            public void Outdent() => _depth--;

            public override string ToString() => _builder.ToString();
        }
    }
}
