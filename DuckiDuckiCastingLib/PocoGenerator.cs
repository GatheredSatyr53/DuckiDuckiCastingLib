using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace DuckiDuckiCastingLib;

[Generator(LanguageNames.CSharp)]
public sealed class PocoGenerator : IIncrementalGenerator
{
    private const string AnnotationsNamespace = "DuckiDuckiCastingLib.Annotations";
    private const string PrototypeAttributeName = "global::" + AnnotationsNamespace + ".PocoPrototypeAttribute";

    private const string FamilyAttributeName = AnnotationsNamespace + ".PocoFamilyAttribute";
    private const string InterfaceAttributeName = "global::" + AnnotationsNamespace + ".PocoInterfaceAttribute";
    private const string BaseAttributeName = "global::" + AnnotationsNamespace + ".PocoBaseAttribute";
    private const string ValueAttributeName = "global::" + AnnotationsNamespace + ".PocoValueAttribute";
    private const string VariableAttributeName = "global::" + AnnotationsNamespace + ".PocoVariableAttribute";

    #pragma warning disable RS2008 // Analyzer release tracking is not used by this project.
    private static readonly DiagnosticDescriptor InvalidSpec = new(
        "POCO001", "Invalid POCO specification", "{0}", "Poco",
        DiagnosticSeverity.Error, isEnabledByDefault: true);
    #pragma warning restore RS2008

    private static readonly SymbolDisplayFormat TypeFormat =
        SymbolDisplayFormat.FullyQualifiedFormat.AddMiscellaneousOptions(
            SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    private static readonly Regex Placeholder = new(
        @"\$\{(?<key>[A-Za-z_][A-Za-z_0-9]*)\}|\$(?<key>[A-Za-z_][A-Za-z_0-9]*)",
        RegexOptions.CultureInvariant);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(output => output.AddSource(
            "PocoPrototypeAttribute.g.cs",
            $$"""
            // <auto-generated/>
            #nullable enable
            namespace {{AnnotationsNamespace}}
            {
                [global::System.AttributeUsage(global::System.AttributeTargets.Class, Inherited = false)]
                internal sealed class PocoPrototypeAttribute : global::System.Attribute
                {
                    public PocoPrototypeAttribute(global::System.Type prototypeType)
                    {
                        PrototypeType = prototypeType;
                    }

                    public global::System.Type PrototypeType { get; }
                }

                [global::System.AttributeUsage(global::System.AttributeTargets.Field | global::System.AttributeTargets.Property | global::System.AttributeTargets.Method, Inherited = false)]
                internal sealed class PocoVariableAttribute : global::System.Attribute
                {
                    public PocoVariableAttribute(string name)
                    {
                        Name = name;
                    }

                    public string Name { get; }
                }

                [global::System.AttributeUsage(global::System.AttributeTargets.Enum)]
                internal sealed class PocoFamilyAttribute : global::System.Attribute
                {
                    public PocoFamilyAttribute(global::System.Type baseType) { }
                    public bool Sealed { get; set; }
                }

                [global::System.AttributeUsage(global::System.AttributeTargets.Enum, AllowMultiple = true)]
                internal sealed class PocoInterfaceAttribute : global::System.Attribute
                {
                    public PocoInterfaceAttribute(global::System.Type interfaceType) { }
                }

                [global::System.AttributeUsage(global::System.AttributeTargets.Field)]
                internal sealed class PocoBaseAttribute : global::System.Attribute
                {
                    public PocoBaseAttribute(global::System.Type genericBase, params global::System.Type[] arguments) { }
                }

                [global::System.AttributeUsage(global::System.AttributeTargets.Field, AllowMultiple = true)]
                internal sealed class PocoValueAttribute : global::System.Attribute
                {
                    public PocoValueAttribute(string name, object value) { }
                }
            }
            """));

        var families = context.SyntaxProvider.ForAttributeWithMetadataName(
            FamilyAttributeName,
            static (node, _) => node is EnumDeclarationSyntax,
            static (attribute, _) => ((INamedTypeSymbol)attribute.TargetSymbol, attribute.Attributes[0]))
            .Collect();

        context.RegisterSourceOutput(context.CompilationProvider.Combine(families), (output, input) =>
        {
            var compilation = (CSharpCompilation)input.Left;
            var drafts = new List<(Location Location, string Name, string Source, SyntaxTree Tree, bool Seal)>();
            var names = new HashSet<string>(StringComparer.Ordinal);
            var parseOptions = compilation.SyntaxTrees.FirstOrDefault()?.Options as CSharpParseOptions
                ?? CSharpParseOptions.Default;

            void AddDraft((string Name, string Source) draft, Location location, bool seal)
            {
                if (!names.Add(draft.Name))
                    throw new SpecException($"Type '{draft.Name}' has multiple specifications.");

                var tree = CSharpSyntaxTree.ParseText(draft.Source, parseOptions, draft.Name + ".g.cs",
                    cancellationToken: output.CancellationToken);
                drafts.Add((location, draft.Name, draft.Source, tree, seal));
            }

            foreach (var (family, attribute) in input.Right)
            {
                if (attribute.ConstructorArguments.Length != 1 ||
                    attribute.ConstructorArguments[0].Value is not INamedTypeSymbol baseType)
                {
                    Report(output, family.Locations[0], "PocoFamily must specify a base class.");
                    continue;
                }

                IReadOnlyList<INamedTypeSymbol> interfaces;
                try
                {
                    interfaces = ReadInterfaces(family);
                }
                catch (SpecException error)
                {
                    Report(output, family.Locations[0], error.Message);
                    continue;
                }

                var seal = attribute.NamedArguments.Any(pair => pair.Key == "Sealed" && pair.Value.Value is true);
                foreach (var field in family.GetMembers().OfType<IFieldSymbol>().Where(field => field.HasConstantValue))
                {
                    output.CancellationToken.ThrowIfCancellationRequested();
                    try
                    {
                        var ns = family.ContainingNamespace.IsGlobalNamespace ? "" : family.ContainingNamespace.ToDisplayString();
                        AddDraft(GenerateFamilyDraft(compilation, ns, field, baseType, interfaces),
                            field.Locations[0], seal);
                    }
                    catch (SpecException error)
                    {
                        Report(output, field.Locations[0], error.Message);
                    }
                }
            }

            // Ask the compiler to resolve inherited abstract slots across all partial declarations.
            var probe = compilation.AddSyntaxTrees(drafts.Select(draft => draft.Tree));
            foreach (var draft in drafts)
            {
                var errors = probe.GetSemanticModel(draft.Tree)
                    .GetDiagnostics(cancellationToken: output.CancellationToken)
                    .Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error)
                    .ToArray();
                var otherErrors = errors.Where(diagnostic => diagnostic.Id != "CS0534").ToArray();
                foreach (var error in otherErrors)
                    Report(output, draft.Location, error.GetMessage());
                if (otherErrors.Length != 0)
                    continue;

                var source = errors.Any(diagnostic => diagnostic.Id == "CS0534")
                    ? draft.Source.Replace("\n    public partial class ", "\n    public abstract partial class ")
                    : draft.Seal
                        ? draft.Source.Replace("\n    public partial class ", "\n    public sealed partial class ")
                        : draft.Source;
                output.AddSource(draft.Name + ".g.cs", SourceText.From(source, Encoding.UTF8));
            }
        });
    }

    private static void Report(SourceProductionContext output, Location location, string message) =>
        output.ReportDiagnostic(Diagnostic.Create(InvalidSpec, location, message));

    private static (string Name, string Source) GenerateFamilyDraft(CSharpCompilation compilation, string ns,
        IFieldSymbol field, INamedTypeSymbol familyBase, IReadOnlyList<INamedTypeSymbol> interfaces)
    {
        var fullName = ns.Length == 0 ? field.Name : ns + "." + field.Name;
        var self = compilation.Assembly.GetTypeByMetadataName(fullName);
        var (baseType, baseSyntax) = SelectBase(field, familyBase, self);
        var variables = new Dictionary<string, ScalarValue>(StringComparer.Ordinal);
        foreach (var attribute in field.GetAttributes().Where(attribute =>
            attribute.AttributeClass?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) == ValueAttributeName))
        {
            var args = attribute.ConstructorArguments;
            if (args.Length != 2 || args[0].Value is not string key || string.IsNullOrWhiteSpace(key))
                throw new SpecException("PocoValue must specify a variable name and value.");
            if (variables.ContainsKey(key))
                throw new SpecException($"Prototype variable '{key}' is assigned more than once.");

            variables.Add(key, AttributeValue(args[1], key));
        }

        var properties = new Dictionary<string, ScalarValue>(StringComparer.Ordinal);
        var methods = new Dictionary<string, ScalarValue>(StringComparer.Ordinal);
        var seen = new HashSet<string>(StringComparer.Ordinal);
        for (var type = baseType; type is not null; type = type.BaseType)
        {
            foreach (var member in type.GetMembers())
            {
                if (member.IsStatic || member.DeclaredAccessibility == Accessibility.Private)
                    continue;
                var signature = member switch
                {
                    IPropertySymbol { IsIndexer: false } => member.Name,
                    IMethodSymbol { MethodKind: MethodKind.Ordinary, Arity: 0, Parameters.Length: 0 } => member.Name + "()",
                    _ => null
                };
                if (signature is null || !seen.Add(signature))
                    continue;

                var binding = member.GetAttributes().FirstOrDefault(attribute =>
                    attribute.AttributeClass?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) == VariableAttributeName);
                if (binding is null)
                    continue;
                if (binding.ConstructorArguments.Length != 1 ||
                    binding.ConstructorArguments[0].Value is not string key || string.IsNullOrWhiteSpace(key))
                    throw new SpecException($"PocoVariable on '{signature}' must specify a variable name.");

                if (variables.TryGetValue(key, out var value))
                    (member is IPropertySymbol ? properties : methods).Add(signature, value);
            }
        }

        var prototype = FindPrototype(baseType);
        return GenerateDraft(compilation, ns, field.Name, baseType, baseSyntax, interfaces, prototype,
            variables, properties, methods);
    }

    private static (INamedTypeSymbol Type, string Syntax) SelectBase(
        IFieldSymbol field, INamedTypeSymbol familyBase, INamedTypeSymbol? self)
    {
        if (familyBase.TypeKind != TypeKind.Class || !familyBase.IsAbstract || familyBase.IsStatic || familyBase.IsGenericType)
            throw new SpecException("PocoFamily must specify a non-generic abstract base class.");

        var attribute = field.GetAttributes().FirstOrDefault(candidate =>
            candidate.AttributeClass?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) == BaseAttributeName);
        if (attribute is null)
            return (familyBase, familyBase.ToDisplayString(TypeFormat));

        var args = attribute.ConstructorArguments;
        if (args.Length != 2 || args[0].Value is not INamedTypeSymbol { IsUnboundGenericType: true } open ||
            open.ContainingType?.IsGenericType == true || args[1].Kind != TypedConstantKind.Array || args[1].IsNull)
            throw new SpecException("PocoBase requires an unbound generic class and its arguments after the generated type.");

        var definition = open.OriginalDefinition;
        var additional = args[1].Values.Select(value => value.Value as ITypeSymbol).ToArray();
        if (definition.TypeKind != TypeKind.Class || !definition.IsAbstract || definition.IsStatic ||
            definition.Arity != additional.Length + 1 ||
            additional.Any(type => type is null || type.TypeKind == TypeKind.Error ||
                type is INamedTypeSymbol { IsUnboundGenericType: true }))
            throw new SpecException("PocoBase must name an abstract generic class with one slot for the generated type plus one per supplied argument.");

        // A newly generated class has no symbol yet. Use the first type parameter for member lookup;
        // the emitted base clause uses the real class name and Roslyn checks constraints on the draft.
        var constructed = definition.Construct(new[] { (ITypeSymbol?)self ?? definition.TypeParameters[0] }
            .Concat(additional.Select(type => type!)).ToArray());
        if (!BaseChain(constructed).Any(type => SymbolEqualityComparer.Default.Equals(type, familyBase)))
            throw new SpecException("PocoBase must derive from the PocoFamily base class.");

        var typeName = definition.ToDisplayString(TypeFormat.WithGenericsOptions(SymbolDisplayGenericsOptions.None));
        var typeArguments = new[] { "@" + field.Name }.Concat(additional.Select(type => type!.ToDisplayString(TypeFormat)));
        return (constructed, typeName + "<" + string.Join(", ", typeArguments) + ">");
    }

    private static IEnumerable<INamedTypeSymbol> BaseChain(INamedTypeSymbol baseType)
    {
        for (var type = baseType; type is not null; type = type.BaseType)
            yield return type;
    }

    private static IReadOnlyList<INamedTypeSymbol> ReadInterfaces(INamedTypeSymbol family)
    {
        var interfaces = new List<INamedTypeSymbol>();
        var seen = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        foreach (var attribute in family.GetAttributes())
        {
            if (attribute.AttributeClass?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) != InterfaceAttributeName)
                continue;
            if (attribute.ConstructorArguments.Length != 1 ||
                attribute.ConstructorArguments[0].Value is not INamedTypeSymbol
                    { TypeKind: TypeKind.Interface, IsUnboundGenericType: false } type)
                throw new SpecException("PocoInterface must name a closed interface.");
            if (seen.Add(type))
                interfaces.Add(type);
        }

        return interfaces;
    }

    private static void AppendStaticProperties(StringBuilder source, IReadOnlyList<INamedTypeSymbol> interfaces,
        INamedTypeSymbol? existing, Dictionary<string, ScalarValue> variables)
    {
        var emitted = new Dictionary<string, (ITypeSymbol Type, string Literal)>(StringComparer.Ordinal);
        var visited = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);
        foreach (var type in interfaces.SelectMany(contract => new[] { contract }.Concat(contract.AllInterfaces)))
        {
            if (!visited.Add(type))
                continue;

            foreach (var property in type.GetMembers().OfType<IPropertySymbol>())
            {
                var binding = property.GetAttributes().FirstOrDefault(attribute =>
                    attribute.AttributeClass?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) == VariableAttributeName);
                if (binding is null)
                    continue;
                if (!property.IsStatic || !property.IsAbstract || property.GetMethod is null ||
                    property.SetMethod is not null || property.ReturnsByRef || property.ReturnsByRefReadonly)
                    throw new SpecException($"PocoVariable on interface property '{property.Name}' requires a static abstract get-only property.");

                if (binding.ConstructorArguments.Length != 1 ||
                    binding.ConstructorArguments[0].Value is not string key || string.IsNullOrWhiteSpace(key))
                    throw new SpecException($"PocoVariable on '{property.Name}' must specify a variable name.");
                if (!variables.ContainsKey(key) && existing?.GetMembers(property.Name).Length > 0)
                    continue;

                var literal = RenderValue(RequiredVariable(variables, key), property.Type, property.Name);
                if (emitted.TryGetValue(property.Name, out var prior))
                {
                    if (!SymbolEqualityComparer.Default.Equals(prior.Type, property.Type) || prior.Literal != literal)
                        throw new SpecException($"Static property '{property.Name}' has conflicting bindings.");
                    continue;
                }

                emitted.Add(property.Name, (property.Type, literal));
                source.Append("        public static ").Append(property.Type.ToDisplayString(TypeFormat))
                    .Append(" @").Append(property.Name).Append(" => ").Append(literal).AppendLine(";");
            }
        }
    }

    private static ScalarValue AttributeValue(TypedConstant argument, string key)
    {
        if (argument.Kind is TypedConstantKind.Error or TypedConstantKind.Array)
            throw new SpecException($"Cannot resolve PocoValue for '{key}'.");

        var value = argument.Value;
        if (argument.Kind == TypedConstantKind.Enum && argument.Type is INamedTypeSymbol enumType)
        {
            value = enumType.GetMembers().OfType<IFieldSymbol>()
                .FirstOrDefault(field => field.HasConstantValue && Equals(field.ConstantValue, value))?.Name
                ?? throw new SpecException($"PocoValue for '{key}' must name a declared enum value.");
        }

        var (kind, text) = value switch
        {
            null => (ScalarKind.Null, ""),
            string str => (ScalarKind.String, str),
            char character => (ScalarKind.String, character.ToString()),
            bool boolean => (ScalarKind.Boolean, boolean ? "true" : "false"),
            float number => (ScalarKind.Number, number.ToString("R", CultureInfo.InvariantCulture)),
            double number => (ScalarKind.Number, number.ToString("R", CultureInfo.InvariantCulture)),
            byte or sbyte or short or ushort or int or uint or long or ulong =>
                (ScalarKind.Number, Convert.ToString(value, CultureInfo.InvariantCulture)!),
            _ => throw new SpecException($"PocoValue for '{key}' must be a scalar constant.")
        };
        return new ScalarValue(kind, text);
    }

    private static (string Name, string Source) GenerateDraft(CSharpCompilation compilation,
        string ns, string name, INamedTypeSymbol baseType, string baseSyntax, IReadOnlyList<INamedTypeSymbol> interfaces, INamedTypeSymbol? prototype,
        Dictionary<string, ScalarValue> variables, Dictionary<string, ScalarValue> properties, Dictionary<string, ScalarValue> methods)
    {
        if (!Identifier(name) || (ns.Length != 0 && !ns.Split('.').All(Identifier)))
            throw new SpecException("Invalid class or namespace name.");

        var fullName = ns.Length == 0 ? name : ns + "." + name;
        if (baseType.TypeKind != TypeKind.Class || !baseType.IsAbstract || baseType.IsStatic ||
            baseType.ToDisplayString() == fullName)
            throw new SpecException("'baseType' must name a different abstract class.");

        var existing = compilation.Assembly.GetTypeByMetadataName(fullName);
        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");
        if (ns.Length != 0)
        {
            source.Append("namespace ").AppendLine(ns);
            source.AppendLine("{");
        }
        if (prototype is not null)
        {
            foreach (var attribute in prototype.GetAttributes().Where(attribute => !IsPrototypeAttribute(attribute)))
                source.Append("    ").AppendLine(RenderAttribute(attribute, variables));
        }

        source.Append("    public partial class ").Append(name).Append(" : ").Append(baseSyntax);
        foreach (var type in interfaces)
            source.Append(", ").Append(type.ToDisplayString(TypeFormat));

        source.AppendLine();
        source.AppendLine("    {");
        AppendStaticProperties(source, interfaces, existing, variables);
        if (prototype is not null)
        {
            foreach (var field in prototype.GetMembers().OfType<IFieldSymbol>())
                AppendPrototypeConstant(source, field, existing, variables);
        }

        foreach (var entry in properties)
        {
            var key = entry.Key;
            var value = entry.Value;
            var member = FindMember(baseType, key, method: false);
            if (member is not IPropertySymbol { GetMethod: not null, SetMethod: null, ReturnsByRef: false, ReturnsByRefReadonly: false } property)
                throw new SpecException($"'{key}' must name an overridable get-only property.");

            if (existing?.GetMembers(key).Length > 0)
                throw new SpecException($"'{key}' is already declared in a handwritten partial class.");
            AppendMember(source, property, key, property.Type, value, compilation);
        }

        foreach (var entry in methods)
        {
            var key = entry.Key;
            var value = entry.Value;
            if (!key.EndsWith("()", StringComparison.Ordinal))
                throw new SpecException($"Expected a parameterless method signature, got '{key}'.");
            var memberName = key.Substring(0, key.Length - 2);
            var member = FindMember(baseType, memberName, method: true);
            if (member is not IMethodSymbol { ReturnsVoid: false, ReturnsByRef: false, ReturnsByRefReadonly: false } method)
                throw new SpecException($"'{key}' must name an overridable parameterless method with a return value.");

            if (existing?.GetMembers(memberName).Any(symbol => symbol is not IMethodSymbol methodSymbol ||
                (methodSymbol.Arity == 0 && methodSymbol.Parameters.Length == 0)) == true)
                throw new SpecException($"'{key}' is already declared in a handwritten partial class.");
            AppendMember(source, method, key, method.ReturnType, value, compilation);
        }

        source.AppendLine("    }");
        if (ns.Length != 0)
            source.AppendLine("}");
        return (fullName, source.ToString());
    }

    private static bool Identifier(string value) =>
        SyntaxFacts.IsValidIdentifier(value) && SyntaxFacts.GetKeywordKind(value) == SyntaxKind.None &&
        !value.StartsWith("@", StringComparison.Ordinal);

    private static bool IsPrototypeAttribute(AttributeData attribute) =>
        attribute.AttributeClass?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) == PrototypeAttributeName;

    private static INamedTypeSymbol? FindPrototype(INamedTypeSymbol baseType)
    {
        var attribute = BaseChain(baseType).SelectMany(type => type.GetAttributes()).FirstOrDefault(IsPrototypeAttribute);
        if (attribute is not null)
        {
            if (attribute.ConstructorArguments.Length == 1 &&
                attribute.ConstructorArguments[0].Value is INamedTypeSymbol { TypeKind: TypeKind.Class } prototype)
                return prototype;

            throw new SpecException($"PocoPrototype on '{baseType.ToDisplayString()}' must reference a class.");
        }

        return null;
    }

    private static ISymbol? FindMember(INamedTypeSymbol baseType, string name, bool method)
    {
        if (!Identifier(name))
            return null;

        for (var type = baseType; type is not null; type = type.BaseType)
        {
            foreach (var member in type.GetMembers(name))
            {
                if (member.IsStatic || member.DeclaredAccessibility == Accessibility.Private)
                    continue;
                if (method && member is IMethodSymbol { MethodKind: MethodKind.Ordinary, Arity: 0, Parameters.Length: 0 } ||
                    !method && member is IPropertySymbol { IsIndexer: false })
                {
                    return !member.IsSealed && (member.IsAbstract || member.IsVirtual || member.IsOverride)
                        ? member
                        : null;
                }
            }
        }

        return null;
    }

    private static void AppendPrototypeConstant(StringBuilder source, IFieldSymbol field,
        INamedTypeSymbol? existing, Dictionary<string, ScalarValue> variables)
    {
        var binding = field.GetAttributes().FirstOrDefault(attribute =>
            attribute.AttributeClass?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) == VariableAttributeName);
        if (!field.IsConst)
        {
            if (binding is not null)
                throw new SpecException($"PocoVariable on '{field.Name}' requires a const field.");
            return;
        }

        if (existing?.GetMembers(field.Name).Length > 0)
            throw new SpecException($"Constant '{field.Name}' is already declared in a handwritten partial class.");
        if (!field.HasConstantValue)
            throw new SpecException($"Cannot resolve the value of prototype constant '{field.Name}'.");

        string literal;
        if (binding is not null)
        {
            if (binding.ConstructorArguments.Length != 1 ||
                binding.ConstructorArguments[0].Value is not string key || string.IsNullOrWhiteSpace(key))
                throw new SpecException($"PocoVariable on '{field.Name}' must specify a variable name.");

            literal = RenderValue(RequiredVariable(variables, key), field.Type,
                $"{field.Name} (variables.{key})");
        }
        else
        {
            literal = RenderConstant(field, variables);
        }

        var accessibility = field.DeclaredAccessibility switch
        {
            Accessibility.Public => "public",
            Accessibility.Internal => "internal",
            Accessibility.Protected => "protected",
            Accessibility.ProtectedAndInternal => "private protected",
            Accessibility.ProtectedOrInternal => "protected internal",
            _ => "private"
        };

        source.Append("        ").Append(accessibility).Append(" const ").Append(field.Type.ToDisplayString(TypeFormat))
            .Append(" @").Append(field.Name).Append(" = ").Append(literal).AppendLine(";");
    }

    private static string RenderConstant(IFieldSymbol field, Dictionary<string, ScalarValue> variables)
    {
        var literal = field.ConstantValue switch
        {
            null => "null",
            string template => RenderTemplate(template, variables),
            char character => SymbolDisplay.FormatLiteral(character, quote: true),
            decimal number => number.ToString(CultureInfo.InvariantCulture) + "M",
            float number when float.IsNaN(number) => "float.NaN",
            float number when float.IsPositiveInfinity(number) => "float.PositiveInfinity",
            float number when float.IsNegativeInfinity(number) => "float.NegativeInfinity",
            float number => number.ToString("R", CultureInfo.InvariantCulture) + "F",
            double number when double.IsNaN(number) => "double.NaN",
            double number when double.IsPositiveInfinity(number) => "double.PositiveInfinity",
            double number when double.IsNegativeInfinity(number) => "double.NegativeInfinity",
            double number => number.ToString("R", CultureInfo.InvariantCulture) + "D",
            uint number => number.ToString(CultureInfo.InvariantCulture) + "U",
            long number => number.ToString(CultureInfo.InvariantCulture) + "L",
            ulong number => number.ToString(CultureInfo.InvariantCulture) + "UL",
            object value => SymbolDisplay.FormatPrimitive(value, quoteStrings: true, useHexadecimalNumbers: false)
        };

        return field.Type.TypeKind == TypeKind.Enum ? "(" + field.Type.ToDisplayString(TypeFormat) + ")(" + literal + ")" : literal;
    }

    private static void AppendMember(StringBuilder source, ISymbol member, string signature, ITypeSymbol type,
        ScalarValue value, Compilation compilation)
    {
        var accessibility = member.DeclaredAccessibility switch
        {
            Accessibility.Public => "public",
            Accessibility.Protected => "protected",
            Accessibility.Internal => "internal",
            Accessibility.ProtectedAndInternal => "private protected",
            Accessibility.ProtectedOrInternal =>
                SymbolEqualityComparer.Default.Equals(member.ContainingAssembly, compilation.Assembly)
                    ? "protected internal" : "protected",
            _ => throw new SpecException($"Unsupported accessibility for '{signature}'.")
        };

        var literal = RenderValue(value, type, signature);
        source.Append("        ").Append(accessibility).Append(" override ").Append(type.ToDisplayString(TypeFormat))
            .Append(' ').Append(signature).Append(" => ").Append(literal).AppendLine(";");
    }

    private static string RenderValue(ScalarValue value, ITypeSymbol type, string signature)
    {
        var nullableValue = type is INamedTypeSymbol named &&
            named.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T;
        if (value.Kind == ScalarKind.Null && (type.IsReferenceType || nullableValue))
            return "null";

        if (nullableValue)
            type = ((INamedTypeSymbol)type).TypeArguments[0];
        if (type.TypeKind == TypeKind.Enum && value.Kind == ScalarKind.String)
        {
            var field = type.GetMembers(value.Value).OfType<IFieldSymbol>().FirstOrDefault(item => item.HasConstantValue);
            if (field is not null)
                return type.ToDisplayString(TypeFormat) + ".@" + field.Name;
        }

        switch (type.SpecialType, value.Kind)
        {
            case (SpecialType.System_String, ScalarKind.String):
                return SymbolDisplay.FormatLiteral(value.Value, quote: true);
            case (SpecialType.System_Char, ScalarKind.String) when value.Value.Length == 1:
                return SymbolDisplay.FormatLiteral(value.Value[0], quote: true);
            case (SpecialType.System_Boolean, ScalarKind.Boolean):
                return value.Value;
        }

        if (value.Kind == ScalarKind.Number)
        {
            var number = type.SpecialType switch
            {
                SpecialType.System_Byte when byte.TryParse(value.Value, NumberStyles.AllowLeadingSign, CultureInfo.InvariantCulture, out var n) => n.ToString(CultureInfo.InvariantCulture),
                SpecialType.System_SByte when sbyte.TryParse(value.Value, NumberStyles.AllowLeadingSign, CultureInfo.InvariantCulture, out var n) => n.ToString(CultureInfo.InvariantCulture),
                SpecialType.System_Int16 when short.TryParse(value.Value, NumberStyles.AllowLeadingSign, CultureInfo.InvariantCulture, out var n) => n.ToString(CultureInfo.InvariantCulture),
                SpecialType.System_UInt16 when ushort.TryParse(value.Value, NumberStyles.AllowLeadingSign, CultureInfo.InvariantCulture, out var n) => n.ToString(CultureInfo.InvariantCulture),
                SpecialType.System_Int32 when int.TryParse(value.Value, NumberStyles.AllowLeadingSign, CultureInfo.InvariantCulture, out var n) => n.ToString(CultureInfo.InvariantCulture),
                SpecialType.System_UInt32 when uint.TryParse(value.Value, NumberStyles.AllowLeadingSign, CultureInfo.InvariantCulture, out var n) => n.ToString(CultureInfo.InvariantCulture) + "U",
                SpecialType.System_Int64 when long.TryParse(value.Value, NumberStyles.AllowLeadingSign, CultureInfo.InvariantCulture, out var n) => n.ToString(CultureInfo.InvariantCulture) + "L",
                SpecialType.System_UInt64 when ulong.TryParse(value.Value, NumberStyles.AllowLeadingSign, CultureInfo.InvariantCulture, out var n) => n.ToString(CultureInfo.InvariantCulture) + "UL",
                SpecialType.System_Single when float.TryParse(value.Value, NumberStyles.Float, CultureInfo.InvariantCulture, out var n) && !float.IsInfinity(n) && !float.IsNaN(n) =>
                    n.ToString("R", CultureInfo.InvariantCulture) + "F",
                SpecialType.System_Double when double.TryParse(value.Value, NumberStyles.Float, CultureInfo.InvariantCulture, out var n) && !double.IsInfinity(n) && !double.IsNaN(n) =>
                    n.ToString("R", CultureInfo.InvariantCulture) + "D",
                SpecialType.System_Decimal when decimal.TryParse(value.Value, NumberStyles.Float, CultureInfo.InvariantCulture, out var n) =>
                    n.ToString(CultureInfo.InvariantCulture) + "M",
                _ => null
            };
            if (number is not null)
                return number;
        }

        throw new SpecException($"Value for '{signature}' is incompatible with '{type.ToDisplayString()}'.");
    }

    private static string RenderAttribute(AttributeData attribute, Dictionary<string, ScalarValue> variables)
    {
        var type = attribute.AttributeClass ?? throw new SpecException("Cannot resolve a prototype attribute.");
        var args = attribute.ConstructorArguments.Select(value => RenderAttributeValue(value, variables))
            .Concat(attribute.NamedArguments.Select(pair => "@" + pair.Key + " = " + RenderAttributeValue(pair.Value, variables)));
        return "[" + type.ToDisplayString(TypeFormat) + "(" + string.Join(", ", args) + ")]";
    }

    private static string RenderAttributeValue(TypedConstant value, Dictionary<string, ScalarValue> variables)
    {
        if (value.Type is null || value.Kind == TypedConstantKind.Error)
            throw new SpecException("Cannot resolve a prototype attribute argument.");

        var type = value.Type.ToDisplayString(TypeFormat);
        if (value.IsNull)
            return "(" + type + ")null";
        if (value.Kind == TypedConstantKind.Array)
        {
            return "new " + type + " { " +
                string.Join(", ", value.Values.Select(item => RenderAttributeValue(item, variables))) + " }";
        }

        if (value.Kind == TypedConstantKind.Type && value.Value is ITypeSymbol typeValue)
            return "typeof(" + typeValue.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ")";
        if (value.Value is string template)
            return RenderTemplate(template, variables);

        if (value.Value is null)
            throw new SpecException("Unsupported prototype attribute argument.");
        return "(" + type + ")(" + SymbolDisplay.FormatPrimitive(value.Value, quoteStrings: true, useHexadecimalNumbers: false) + ")";
    }

    private static ScalarValue RequiredVariable(Dictionary<string, ScalarValue> variables, string key) =>
        variables.TryGetValue(key, out var value) ? value : throw new SpecException($"Missing prototype variable '{key}'.");

    private static string RenderTemplate(string template, Dictionary<string, ScalarValue> variables)
    {
        var expanded = Placeholder.Replace(template, match =>
        {
            var key = match.Groups["key"].Value;
            var value = RequiredVariable(variables, key);
            if (value.Kind != ScalarKind.String)
                throw new SpecException($"Prototype variable '{key}' must be a string for template substitution.");
            return value.Value;
        });
        return SymbolDisplay.FormatLiteral(expanded, quote: true);
    }

    private enum ScalarKind { Null, String, Boolean, Number }

    private readonly record struct ScalarValue(ScalarKind Kind, string Value);

    private sealed class SpecException : Exception
    {
        public SpecException(string message) : base(message)
        {
        }
    }
