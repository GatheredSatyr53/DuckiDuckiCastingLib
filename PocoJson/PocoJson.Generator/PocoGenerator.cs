using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace PocoJson;

[Generator(LanguageNames.CSharp)]
public sealed class PocoGenerator : IIncrementalGenerator
{
    private const string PrototypeAttributeName = "global::PocoJson.PocoPrototypeAttribute";

    private static readonly DiagnosticDescriptor InvalidSpec = new(
        "POCO001", "Invalid POCO specification", "{0}", "PocoJson",
        DiagnosticSeverity.Error, isEnabledByDefault: true);

    private static readonly SymbolDisplayFormat TypeFormat =
        SymbolDisplayFormat.FullyQualifiedFormat.AddMiscellaneousOptions(
            SymbolDisplayMiscellaneousOptions.IncludeNullableReferenceTypeModifier);

    private static readonly Regex Placeholder = new(
        @"\$\{(?<key>[A-Za-z_][A-Za-z_0-9]*)\}|\$(?<key>[A-Za-z_][A-Za-z_0-9]*)",
        RegexOptions.CultureInvariant);

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(output => output.AddSource(
            "PocoJson.PocoPrototypeAttribute.g.cs",
            """
            // <auto-generated/>
            namespace PocoJson
            {
                [global::System.AttributeUsage(global::System.AttributeTargets.Class, Inherited = false)]
                internal sealed class PocoPrototypeAttribute : global::System.Attribute
                {
                    public PocoPrototypeAttribute(global::System.Type prototypeType)
                    {
                        PrototypeType = prototypeType;
                    }

                    public global::System.Type PrototypeType { get; }
                }
            }
            """));

        var specs = context.AdditionalTextsProvider
            .Where(file => file.Path.EndsWith(".stage.json", StringComparison.OrdinalIgnoreCase))
            .Select((file, token) => (file.Path, Text: file.GetText(token)?.ToString()))
            .Collect();

        context.RegisterSourceOutput(context.CompilationProvider.Combine(specs), (output, input) =>
        {
            var compilation = (CSharpCompilation)input.Left;
            var drafts = new List<(string Path, string Name, string Source, SyntaxTree Tree)>();
            var names = new HashSet<string>(StringComparer.Ordinal);
            var parseOptions = compilation.SyntaxTrees.FirstOrDefault()?.Options as CSharpParseOptions
                ?? CSharpParseOptions.Default;

            foreach (var spec in input.Right.OrderBy(spec => spec.Path, StringComparer.Ordinal))
            {
                output.CancellationToken.ThrowIfCancellationRequested();
                try
                {
                    using var json = JsonDocument.Parse(spec.Text ?? throw new SpecException("Cannot read file."));
                    var (name, source) = GenerateDraft(compilation, json.RootElement);
                    if (!names.Add(name))
                        throw new SpecException($"Type '{name}' has multiple specifications.");

                    var tree = CSharpSyntaxTree.ParseText(source, parseOptions, spec.Path + ".g.cs",
                        cancellationToken: output.CancellationToken);
                    drafts.Add((spec.Path, name, source, tree));
                }
                catch (Exception error) when (error is JsonException or SpecException)
                {
                    Report(output, spec.Path, error.Message);
                }
            }

            // Ask the compiler to resolve inherited abstract slots across all partial declarations.
            var probe = compilation.AddSyntaxTrees(drafts.Select(draft => draft.Tree));
            foreach (var draft in drafts)
            {
                var errors = probe.GetSemanticModel(draft.Tree)
                    .GetDiagnostics(cancellationToken: output.CancellationToken)
                    .Where(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error)
                    .ToArray();
                var otherErrors = errors.Where(diagnostic => diagnostic.Id != "CS0534").ToArray();
                foreach (var error in otherErrors)
                    Report(output, draft.Path, error.GetMessage());
                if (otherErrors.Length != 0)
                    continue;

                var source = errors.Any(diagnostic => diagnostic.Id == "CS0534")
                    ? draft.Source.Replace("\n    public partial class ", "\n    public abstract partial class ", StringComparison.Ordinal)
                    : draft.Source;
                output.AddSource(draft.Name + ".g.cs", SourceText.From(source, Encoding.UTF8));
            }
        });
    }

    private static void Report(SourceProductionContext output, string path, string message)
    {
        var position = new LinePosition(0, 0);
        var location = Location.Create(path, new TextSpan(0, 0), new LinePositionSpan(position, position));
        output.ReportDiagnostic(Diagnostic.Create(InvalidSpec, location, message));
    }

    private static (string Name, string Source) GenerateDraft(CSharpCompilation compilation, JsonElement root)
    {
        var spec = Object(root, "specification");
        foreach (var key in spec.Keys)
        {
            if (key is not ("namespace" or "name" or "baseType" or "prototype" or "properties" or "methods" or "variables"))
                throw new SpecException($"Unknown field '{key}'.");
        }

        var ns = RequiredString(spec, "namespace");
        var name = RequiredString(spec, "name");
        if (!Identifier(name) || !ns.Split('.').All(Identifier))
            throw new SpecException("Invalid class or namespace name.");

        var fullName = ns + "." + name;
        var baseType = ResolveType(compilation, RequiredString(spec, "baseType"));
        if (baseType.TypeKind != TypeKind.Class || !baseType.IsAbstract || baseType.IsStatic ||
            baseType.IsGenericType || baseType.ToDisplayString() == fullName)
            throw new SpecException("'baseType' must name a different non-generic abstract class.");

        var existing = compilation.Assembly.GetTypeByMetadataName(fullName);
        var variables = OptionalObject(spec, "variables").ToDictionary(pair => pair.Key,
            pair => StringValue(pair.Value, pair.Key), StringComparer.Ordinal);

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated/>");
        source.AppendLine("#nullable enable");
        source.Append("namespace ").AppendLine(ns);
        source.AppendLine("{");
        var prototype = FindPrototype(compilation, baseType, spec);
        if (prototype is not null)
        {
            foreach (var attribute in prototype.GetAttributes().Where(attribute => !IsPrototypeAttribute(attribute)))
                source.Append("    ").AppendLine(RenderAttribute(attribute, variables));
        }

        source.Append("    public partial class ").Append(name).Append(" : ")
            .AppendLine(baseType.ToDisplayString(TypeFormat));
        source.AppendLine("    {");
        foreach (var (key, value) in OptionalObject(spec, "properties"))
        {
            var member = FindMember(baseType, key, method: false);
            if (member is not IPropertySymbol { GetMethod: not null, SetMethod: null, ReturnsByRef: false, ReturnsByRefReadonly: false } property)
                throw new SpecException($"'{key}' must name an overridable get-only property.");

            if (existing?.GetMembers(key).Length > 0)
                throw new SpecException($"'{key}' is already declared in a handwritten partial class.");
            AppendMember(source, property, key, property.Type, value, compilation);
        }

        foreach (var (key, value) in OptionalObject(spec, "methods"))
        {
            if (!key.EndsWith("()", StringComparison.Ordinal))
                throw new SpecException($"Expected a parameterless method signature, got '{key}'.");
            var memberName = key[..^2];
            var member = FindMember(baseType, memberName, method: true);
            if (member is not IMethodSymbol { ReturnsVoid: false, ReturnsByRef: false, ReturnsByRefReadonly: false } method)
                throw new SpecException($"'{key}' must name an overridable parameterless method with a return value.");

            if (existing?.GetMembers(memberName).Any(symbol => symbol is not IMethodSymbol methodSymbol ||
                (methodSymbol.Arity == 0 && methodSymbol.Parameters.Length == 0)) == true)
                throw new SpecException($"'{key}' is already declared in a handwritten partial class.");
            AppendMember(source, method, key, method.ReturnType, value, compilation);
        }

        source.AppendLine("    }");
        source.AppendLine("}");
        return (fullName, source.ToString());
    }

    private static bool Identifier(string value) =>
        SyntaxFacts.IsValidIdentifier(value) && SyntaxFacts.GetKeywordKind(value) == SyntaxKind.None &&
        !value.StartsWith('@');

    private static INamedTypeSymbol ResolveType(Compilation compilation, string name) =>
        compilation.GetTypeByMetadataName(name) ?? throw new SpecException($"Unknown or ambiguous type '{name}'.");

    private static bool IsPrototypeAttribute(AttributeData attribute) =>
        attribute.AttributeClass?.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) == PrototypeAttributeName;

    private static INamedTypeSymbol? FindPrototype(Compilation compilation, INamedTypeSymbol baseType,
        Dictionary<string, JsonElement> spec)
    {
        var attribute = baseType.GetAttributes().FirstOrDefault(IsPrototypeAttribute);
        if (attribute is not null)
        {
            if (attribute.ConstructorArguments.Length == 1 &&
                attribute.ConstructorArguments[0].Value is INamedTypeSymbol { TypeKind: TypeKind.Class } prototype)
                return prototype;

            throw new SpecException($"PocoPrototype on '{baseType.ToDisplayString()}' must reference a class.");
        }

        return spec.TryGetValue("prototype", out var prototypeName)
            ? ResolveType(compilation, StringValue(prototypeName, "prototype"))
            : null;
    }

    private static ISymbol? FindMember(INamedTypeSymbol baseType, string name, bool method)
    {
        if (!Identifier(name))
            return null;

        for (var type = baseType; type is not null; type = type.BaseType)
        {
            foreach (var member in type.GetMembers(name))
            {
                if (member.IsStatic || member.DeclaredAccessibility == Accessibility.Private)
                    continue;
                if (method && member is IMethodSymbol { MethodKind: MethodKind.Ordinary, Arity: 0, Parameters.Length: 0 } ||
                    !method && member is IPropertySymbol { IsIndexer: false })
                {
                    return !member.IsSealed && (member.IsAbstract || member.IsVirtual || member.IsOverride)
                        ? member
                        : null;
                }
            }
        }

        return null;
    }

    private static void AppendMember(StringBuilder source, ISymbol member, string signature, ITypeSymbol type,
        JsonElement value, Compilation compilation)
    {
        var accessibility = member.DeclaredAccessibility switch
        {
            Accessibility.Public => "public",
            Accessibility.Protected => "protected",
            Accessibility.Internal => "internal",
            Accessibility.ProtectedAndInternal => "private protected",
            Accessibility.ProtectedOrInternal =>
                SymbolEqualityComparer.Default.Equals(member.ContainingAssembly, compilation.Assembly)
                    ? "protected internal" : "protected",
            _ => throw new SpecException($"Unsupported accessibility for '{signature}'.")
        };

        var literal = RenderValue(value, type, signature);
        source.Append("        ").Append(accessibility).Append(" override ").Append(type.ToDisplayString(TypeFormat))
            .Append(' ').Append(signature).Append(" => ").Append(literal).AppendLine(";");
    }

    private static string RenderValue(JsonElement value, ITypeSymbol type, string signature)
    {
        var nullableValue = type is INamedTypeSymbol named &&
            named.OriginalDefinition.SpecialType == SpecialType.System_Nullable_T;
        if (value.ValueKind == JsonValueKind.Null && (type.IsReferenceType || nullableValue))
            return "null";

        if (nullableValue)
            type = ((INamedTypeSymbol)type).TypeArguments[0];
        if (type.TypeKind == TypeKind.Enum && value.ValueKind == JsonValueKind.String)
        {
            var field = type.GetMembers(value.GetString()!).OfType<IFieldSymbol>().FirstOrDefault(item => item.HasConstantValue);
            if (field is not null)
                return type.ToDisplayString(TypeFormat) + ".@" + field.Name;
        }

        switch (type.SpecialType, value.ValueKind)
        {
            case (SpecialType.System_String, JsonValueKind.String):
                return SymbolDisplay.FormatLiteral(value.GetString()!, quote: true);
            case (SpecialType.System_Char, JsonValueKind.String) when value.GetString()!.Length == 1:
                return SymbolDisplay.FormatLiteral(value.GetString()![0], quote: true);
            case (SpecialType.System_Boolean, JsonValueKind.True):
                return "true";
            case (SpecialType.System_Boolean, JsonValueKind.False):
                return "false";
        }

        if (value.ValueKind == JsonValueKind.Number)
        {
            var number = type.SpecialType switch
            {
                SpecialType.System_Byte when value.TryGetByte(out var n) => n.ToString(CultureInfo.InvariantCulture),
                SpecialType.System_SByte when value.TryGetSByte(out var n) => n.ToString(CultureInfo.InvariantCulture),
                SpecialType.System_Int16 when value.TryGetInt16(out var n) => n.ToString(CultureInfo.InvariantCulture),
                SpecialType.System_UInt16 when value.TryGetUInt16(out var n) => n.ToString(CultureInfo.InvariantCulture),
                SpecialType.System_Int32 when value.TryGetInt32(out var n) => n.ToString(CultureInfo.InvariantCulture),
                SpecialType.System_UInt32 when value.TryGetUInt32(out var n) => n.ToString(CultureInfo.InvariantCulture) + "U",
                SpecialType.System_Int64 when value.TryGetInt64(out var n) => n.ToString(CultureInfo.InvariantCulture) + "L",
                SpecialType.System_UInt64 when value.TryGetUInt64(out var n) => n.ToString(CultureInfo.InvariantCulture) + "UL",
                SpecialType.System_Single when value.TryGetSingle(out var n) && float.IsFinite(n) =>
                    n.ToString("R", CultureInfo.InvariantCulture) + "F",
                SpecialType.System_Double when value.TryGetDouble(out var n) && double.IsFinite(n) =>
                    n.ToString("R", CultureInfo.InvariantCulture) + "D",
                SpecialType.System_Decimal when value.TryGetDecimal(out var n) =>
                    n.ToString(CultureInfo.InvariantCulture) + "M",
                _ => null
            };
            if (number is not null)
                return number;
        }

        throw new SpecException($"Value for '{signature}' is incompatible with '{type.ToDisplayString()}'.");
    }

    private static string RenderAttribute(AttributeData attribute, Dictionary<string, string> variables)
    {
        var type = attribute.AttributeClass ?? throw new SpecException("Cannot resolve a prototype attribute.");
        var args = attribute.ConstructorArguments.Select(value => RenderAttributeValue(value, variables))
            .Concat(attribute.NamedArguments.Select(pair => "@" + pair.Key + " = " + RenderAttributeValue(pair.Value, variables)));
        return "[" + type.ToDisplayString(TypeFormat) + "(" + string.Join(", ", args) + ")]";
    }

    private static string RenderAttributeValue(TypedConstant value, Dictionary<string, string> variables)
    {
        if (value.Type is null || value.Kind == TypedConstantKind.Error)
            throw new SpecException("Cannot resolve a prototype attribute argument.");

        var type = value.Type.ToDisplayString(TypeFormat);
        if (value.IsNull)
            return "(" + type + ")null";
        if (value.Kind == TypedConstantKind.Array)
        {
            return "new " + type + " { " +
                string.Join(", ", value.Values.Select(item => RenderAttributeValue(item, variables))) + " }";
        }

        if (value.Kind == TypedConstantKind.Type && value.Value is ITypeSymbol typeValue)
            return "typeof(" + typeValue.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat) + ")";
        if (value.Value is string template)
        {
            var expanded = Placeholder.Replace(template, match =>
            {
                var key = match.Groups["key"].Value;
                return variables.TryGetValue(key, out var replacement) ? replacement
                    : throw new SpecException($"Missing prototype variable '{key}'.");
            });
            return SymbolDisplay.FormatLiteral(expanded, quote: true);
        }

        if (value.Value is null)
            throw new SpecException("Unsupported prototype attribute argument.");
        return "(" + type + ")(" + SymbolDisplay.FormatPrimitive(value.Value, quoteStrings: true, useHexadecimalNumbers: false) + ")";
    }

    private static Dictionary<string, JsonElement> Object(JsonElement value, string field)
    {
        if (value.ValueKind != JsonValueKind.Object)
            throw new SpecException($"'{field}' must be an object.");

        var result = new Dictionary<string, JsonElement>(StringComparer.Ordinal);
        foreach (var property in value.EnumerateObject())
        {
            if (!result.TryAdd(property.Name, property.Value))
                throw new SpecException($"Duplicate field '{property.Name}' in '{field}'.");
        }

        return result;
    }

    private static Dictionary<string, JsonElement> OptionalObject(Dictionary<string, JsonElement> spec, string key) =>
        spec.TryGetValue(key, out var value) ? Object(value, key) : new(StringComparer.Ordinal);

    private static string RequiredString(Dictionary<string, JsonElement> spec, string key) =>
        spec.TryGetValue(key, out var value) ? StringValue(value, key)
            : throw new SpecException($"Missing field '{key}'.");

    private static string StringValue(JsonElement value, string key) =>
        value.ValueKind == JsonValueKind.String ? value.GetString()!
            : throw new SpecException($"'{key}' must be a string.");

    private sealed class SpecException(string message) : Exception(message);
}
